// Codex plugin (ahood#1009): plugins/codex/ plus the repo-root marketplace
// .agents/plugins/marketplace.json, rendered from the same sources the other
// shells use -- the `ahood` skill from templates/codex.ts (AHOOD_COMMANDS),
// the MCP entry from ahood-commands.ts, the version from package.json. The
// files are committed (Codex installs the plugin straight from this git repo,
// so nothing can generate them at install time); `npm run sync-plugin`
// rewrites them and tests/codex-plugin.test.ts fails when they drift. The
// plugin's using-ahood skill is the self-skill, written by scripts/sync-skill.mjs.
//
// Format mirrored from an installed Codex plugin, PaddleHQ/paddle-agent-skills
// (`paddle@paddle-agent-skills`, codex-cli 0.165.0):
//   - config.toml: `[marketplaces.<name>] source_type = "git" source = <url>`,
//     where <name> is the marketplace.json `name`, then
//     `[plugins."<plugin>@<marketplace>"] enabled = true`.
//   - marketplace.json: `{ name, interface.displayName, plugins: [{ name,
//     source: { source: "local", path }, policy, category }] }`.
//   - plugin.json: `{ name, version, description, ..., skills: "./skills/",
//     mcpServers: "./.mcp.json", interface }`; the plugin is cached per
//     version under $CODEX_HOME/plugins/cache/<marketplace>/<plugin>/<version>.
//   - .mcp.json: `{ mcpServers: { <name>: { type: "http", url,
//     bearer_token_env_var } } }` -- unlike Claude Code's, it is wrapped.
import { CLI_VERSION } from "../../version.js";
import { AHOOD_MCP_TOKEN_ENV, AHOOD_MCP_URL } from "./ahood-commands.js";
import { CODEX_MARKETPLACE_NAME, CODEX_PLUGIN_NAME, codexPluginSkill } from "./codex.js";

export const CODEX_PLUGIN_DIR = "plugins/codex";
export const CODEX_MARKETPLACE_FILE = ".agents/plugins/marketplace.json";

const REPO_URL = "https://github.com/AlexKay28/ahood-cli";
const CATEGORY = "Productivity";
const SHORT_DESCRIPTION = "ahood's registry MCP tools, plus a skill for your dashboard, updates, reviews and snaps";

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

function manifest(): string {
  return json({
    name: CODEX_PLUGIN_NAME,
    version: CLI_VERSION,
    description:
      "ahood in Codex: the registry's MCP tools (search, fetch, publish skills, agents, MCP servers, docs), plus the " +
      "ahood skill for your dashboard, syncing updates, reviewing evolution proposals and capturing private snaps.",
    author: { name: "ahood", url: REPO_URL },
    homepage: "https://www.ahood.dev/docs#mcp",
    repository: REPO_URL,
    license: "MIT",
    keywords: ["skills", "registry", "mcp", "agents", "ahood", "snaps"],
    skills: "./skills/",
    mcpServers: "./.mcp.json",
    interface: {
      displayName: "ahood",
      shortDescription: SHORT_DESCRIPTION,
      longDescription:
        "ahood (ahood.dev) is a registry for AI agent skills, agents, MCP servers and docs, with versioning, private " +
        "session notes (snaps) and owner-approved self-evolution. This plugin wires up ahood's hosted MCP server " +
        `(it reads your token from $${AHOOD_MCP_TOKEN_ENV}) and bundles two skills: \`ahood\`, a dashboard of ` +
        "installed skills that syncs updates and reviews evolution proposals only with your consent, and " +
        "`using-ahood`, how to search, install and snap from inside a session.",
      developerName: "ahood",
      category: CATEGORY,
      capabilities: ["Read", "Write"],
      websiteURL: "https://www.ahood.dev",
      privacyPolicyURL: "https://www.ahood.dev/privacy",
      termsOfServiceURL: "https://www.ahood.dev/terms",
    },
  });
}

// Names the env var, never a token: a plugin is shared from a public repo.
// `ahood setup codex --store-token` cannot put a token here either -- see
// harnesses/codex.ts for where it goes instead.
function mcpConfig(): string {
  return json({
    mcpServers: { ahood: { type: "http", url: AHOOD_MCP_URL, bearer_token_env_var: AHOOD_MCP_TOKEN_ENV } },
  });
}

function marketplace(): string {
  return json({
    name: CODEX_MARKETPLACE_NAME,
    interface: { displayName: "ahood" },
    plugins: [
      {
        name: CODEX_PLUGIN_NAME,
        source: { source: "local", path: `./${CODEX_PLUGIN_DIR}` },
        policy: { installation: "AVAILABLE", authentication: "ON_INSTALL" },
        category: CATEGORY,
      },
    ],
  });
}

/**
 * Every Codex plugin file this module owns, as paths relative to the repo
 * root. plugins/codex/skills/using-ahood/SKILL.md is not here: it is the
 * self-skill, generated by scripts/sync-skill.mjs.
 */
export function codexPluginFiles(): Array<{ file: string; content: string }> {
  return [
    { file: CODEX_MARKETPLACE_FILE, content: marketplace() },
    { file: `${CODEX_PLUGIN_DIR}/.codex-plugin/plugin.json`, content: manifest() },
    { file: `${CODEX_PLUGIN_DIR}/.mcp.json`, content: mcpConfig() },
    { file: `${CODEX_PLUGIN_DIR}/skills/ahood/SKILL.md`, content: codexPluginSkill() },
  ];
}
